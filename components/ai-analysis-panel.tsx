import React, { useState } from "react";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { JudicialDecision, LaborContract } from "@shared/schema";
import { useQuery } from "@tanstack/react-query";
import { Skeleton } from "@/components/ui/skeleton";
import { Badge } from "@/components/ui/badge";
import { CircleCheckBig, CircleDashed, Lightbulb, BarChart, BookOpen, ArrowDownToLine } from "lucide-react";

interface AIAnalysisPanelProps {
  document: JudicialDecision | LaborContract;
  documentType: "judicial" | "contract";
  className?: string;
}

interface AnalysisResult {
  summary: string;
  keyPoints: string[];
  citations: string[];
  recommendations: string[];
}

export function AIAnalysisPanel({ document, documentType, className }: AIAnalysisPanelProps) {
  const { data: analysis, isLoading } = useQuery<AnalysisResult>({
    queryKey: [
      `api/${documentType === "judicial" ? "judicial-decisions" : "labor-contracts"}/${document.id}/analysis`,
    ],
    enabled: Boolean(document?.id),
  });

  if (isLoading) {
    return (
      <Card className={className}>
        <CardHeader>
          <CardTitle>
            <Skeleton className="h-8 w-64" />
          </CardTitle>
          <CardDescription>
            <Skeleton className="h-4 w-full" />
          </CardDescription>
        </CardHeader>
        <CardContent>
          <Skeleton className="h-24 w-full mb-4" />
          <Skeleton className="h-24 w-full" />
        </CardContent>
      </Card>
    );
  }

  // Fallback data in case the analysis is not available
  const analysisData: AnalysisResult = analysis || {
    summary: document?.summary || "AI analysis is being generated for this document.",
    keyPoints: ["Document requires deeper analysis", "Request an AI deep dive for more insights"],
    citations: ["No citations detected"],
    recommendations: ["Request full AI analysis"]
  };

  return (
    <Card className={className}>
      <CardHeader>
        <CardTitle className="flex items-center">
          <Lightbulb className="mr-2 h-5 w-5 text-primary" />
          AI Analysis
        </CardTitle>
        <CardDescription>
          Insights and analysis generated by our AI for this {documentType === "judicial" ? "decision" : "contract"}
        </CardDescription>
      </CardHeader>
      <CardContent>
        <Tabs defaultValue="summary" className="w-full">
          <TabsList className="grid grid-cols-4 mb-4">
            <TabsTrigger value="summary">Summary</TabsTrigger>
            <TabsTrigger value="keyPoints">Key Points</TabsTrigger>
            <TabsTrigger value="citations">Citations</TabsTrigger>
            <TabsTrigger value="recommendations">Insights</TabsTrigger>
          </TabsList>
          
          <TabsContent value="summary" className="space-y-4">
            <div className="text-sm">
              <p>{analysisData.summary}</p>
            </div>
          </TabsContent>
          
          <TabsContent value="keyPoints" className="space-y-4">
            <ul className="space-y-2">
              {analysisData.keyPoints.map((point, index) => (
                <li key={index} className="flex items-start">
                  <CircleCheckBig className="h-5 w-5 mr-2 text-primary shrink-0 mt-0.5" />
                  <span className="text-sm">{point}</span>
                </li>
              ))}
            </ul>
          </TabsContent>
          
          <TabsContent value="citations" className="space-y-4">
            {analysisData.citations.length > 0 ? (
              <ul className="space-y-2">
                {analysisData.citations.map((citation, index) => (
                  <li key={index} className="flex items-start">
                    <BookOpen className="h-5 w-5 mr-2 text-primary shrink-0 mt-0.5" />
                    <span className="text-sm">{citation}</span>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-sm text-muted-foreground">No citations detected in this document.</p>
            )}
          </TabsContent>
          
          <TabsContent value="recommendations" className="space-y-4">
            <ul className="space-y-2">
              {analysisData.recommendations.map((recommendation, index) => (
                <li key={index} className="flex items-start">
                  <Lightbulb className="h-5 w-5 mr-2 text-primary shrink-0 mt-0.5" />
                  <span className="text-sm">{recommendation}</span>
                </li>
              ))}
            </ul>
          </TabsContent>
        </Tabs>
        
        <div className="flex items-center justify-between mt-6 pt-4 border-t border-border">
          <Badge variant="outline" className="flex items-center">
            <CircleDashed className="mr-1 h-3 w-3" />
            <span className="text-xs">AI-Generated Analysis</span>
          </Badge>
          <button className="text-xs flex items-center text-primary hover:text-primary/80">
            <ArrowDownToLine className="mr-1 h-3 w-3" />
            Export Analysis
          </button>
        </div>
      </CardContent>
    </Card>
  );
}